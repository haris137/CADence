def pdf_scanned_copy(src: str, dst: str):
    """Image-only copy of a drawing (no text layer) — simulates a scanned drawing."""
    try:
        import pymupdf as fitz
    except ImportError:
        import fitz
    doc = fitz.open(src)
    out = fitz.open()
    for page in doc:
        pix = page.get_pixmap(dpi=100, colorspace=fitz.csGRAY, alpha=False)
        p = out.new_page(width=page.rect.width, height=page.rect.height)
        p.insert_image(p.rect, stream=pix.tobytes("png"))
    out.save(dst)


