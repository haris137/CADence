def make_csv(path: str):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["Part Number", "Description", "Material", "Stock Size", "Finished Size", "Units", "Op No",
                    "Operation", "Machine", "Cycle Time (min)"])
        for pn, desc, mat, stock, fin, rev, qty, notes in PARTS:
            for (op, d, mc, setup, ct) in ROUTING[pn]:
                w.writerow([pn, desc, mat, stock, fin, "mm", op, d, mc, "" if ct is None else ct])


