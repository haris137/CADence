def make_workbook(path: str):
    import openpyxl
    from openpyxl.styles import Alignment, Font
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Parts"
    ws["A1"] = "ACME PRECISION MACHINING — MANUFACTURING RECORD"
    ws.merge_cells("A1:H1")
    ws["A1"].font = Font(bold=True, size=14)
    ws["A2"] = "Exported 2026-10-20"
    headers = ["Part No", "Description", "Material", "Stock Size (mm)", "Finished Size (mm)", "Rev", "Quantity", "Notes"]
    ws.append([])
    ws.append(headers)
    for p in PARTS:
        ws.append(list(p))
    for col, wdt in zip("ABCDEFGH", (10, 18, 18, 16, 18, 6, 9, 38)):
        ws.column_dimensions[col].width = wdt

    r = wb.create_sheet("Routing")
    r.append(["Part No", "Op", "Operation", "Machine", "Setup", "Cycle Time (min)", "Notes"])
    row = 2
    for pn, ops in ROUTING.items():
        first = row
        for i, (op, desc, mc, setup, ct) in enumerate(ops):
            if pn == 2280:
                pval = 2280 if i == 0 else None          # merged vertically below
            elif pn == 2281:
                pval = 2281 if i == 0 else None          # blank continuation rows
            elif pn == 2282:
                pval = "2282"                            # part number stored as text
            else:
                pval = 2283.0                            # stored as a float
            r.append([pval, op, desc, mc, setup, ct, ""])
            row += 1
        if pn == 2280:
            r.merge_cells(start_row=first, start_column=1, end_row=row - 1, end_column=1)
            r.cell(first, 1).alignment = Alignment(vertical="center")
    insp = wb.create_sheet("Inspection")
    insp.append(["Part No", "Characteristic", "Nominal", "Tolerance", "Gauge"])
    insp.append([2280, "Overall length", 100, "±0.1", "Caliper"])
    insp.append([2280, "Hole diameter", 8.5, "+0.1/-0", "Pin gauge"])
    insp.append([2280, "Thickness", 12, "±0.05", "Micrometer"])
    insp.append([2283, "Hole diameter", 6.6, "±0.1", "Pin gauge"])
    wb.save(path)


