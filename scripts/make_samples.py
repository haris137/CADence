def main(out_dir: Optional[str] = None) -> dict:
    base = out_dir or SAMPLES
    for sub in ("excel", "drawings", "models", "extra"):
        os.makedirs(os.path.join(base, sub), exist_ok=True)
    make_workbook(os.path.join(base, "excel", "manufacturing.xlsx"))
    make_messy_workbook(os.path.join(base, "excel", "manufacturing_messy.xlsx"))
    make_csv(os.path.join(base, "excel", "manufacturing.csv"))
    pdf_plate_2280(os.path.join(base, "drawings", "2280_mounting_plate.pdf"))
    pdf_shaft_2281(os.path.join(base, "drawings", "2281_drive_shaft.pdf"))
    pdf_bracket_2283(os.path.join(base, "drawings", "2283_l_bracket.pdf"))
    try:
        pdf_scanned_copy(os.path.join(base, "drawings", "2280_mounting_plate.pdf"),
                         os.path.join(base, "extra", "2280_drawing_scanned.pdf"))
    except Exception as exc:  # PyMuPDF missing -> skip this optional file
        print("skipped scanned PDF:", exc)
    models = {"2280_plate.igs": iges_plate_2280(), "2281_shaft.iges": iges_shaft_2281(),
              "2282_flange.IGS": iges_flange_2282(), "2283_bracket_inch.igs": iges_bracket_2283_inch()}
    for name, text in models.items():
        with open(os.path.join(base, "models", name), "w", encoding="latin-1", newline="") as fh:
            fh.write(text)
    drawings = ["drawings/2280_mounting_plate.pdf", "drawings/2281_drive_shaft.pdf", "drawings/2283_l_bracket.pdf"]
    model_files = [f"models/{m}" for m in models]
    manifest = {
        "parts": {"2280": "consistent (main demo)", "2281": "Excel length 160 vs drawing/model 150; rev A vs B",
                  "2282": "no PDF drawing (missing-source demo)", "2283": "IGES in inches (unit normalisation demo)",
                  "9999": "does not exist (not-found demo)"},
        "sets": {
            "Standard workbook (manufacturing.xlsx)": ["excel/manufacturing.xlsx"] + drawings + model_files,
            "Messy workbook (cryptic headers, decoys)": ["excel/manufacturing_messy.xlsx"] + drawings + model_files,
            "CSV export": ["excel/manufacturing.csv"] + drawings + model_files,
            "Scanned drawing (no text layer)": ["excel/manufacturing.xlsx", "extra/2280_drawing_scanned.pdf",
                                                "models/2280_plate.igs"],
        },
    }
    with open(os.path.join(base, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
    return manifest


