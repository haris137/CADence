def _draw_common(c, part: str, title: str, material: str, rev: str, scale: str, tol: str, finish: str,
                 notes: Sequence[str], units: str = "MM"):
    from reportlab.lib.colors import black
    W, H = c._pagesize
    c.setStrokeColor(black)
    c.setLineWidth(1.2)
    c.rect(20, 20, W - 40, H - 40)
    # title block (bottom right): label small, value below it, inside cells
    x0, y0, cw, ch = W - 20 - 4 * 105, 20, 105, 30
    cells = [("PART NO", part), ("TITLE", title), ("MATERIAL", material), ("REV", rev),
             ("SCALE", scale), ("UNITS", units), ("TOLERANCES UNLESS OTHERWISE SPECIFIED", tol), ("FINISH", finish),
             ("DRAWN", "SPEC26 TEAM"), ("DATE", "2026-10-20"), ("SHEET", "1 OF 1"), ("PROJECTION", "THIRD ANGLE")]
    c.setLineWidth(0.8)
    for i, (lab, val) in enumerate(cells):
        col, row = i % 4, 2 - i // 4
        x, y = x0 + col * cw, y0 + row * ch
        c.rect(x, y, cw, ch)
        c.setFont("Helvetica", 5.5 if len(lab) > 20 else 6.5)
        c.drawString(x + 3, y + ch - 8, lab)
        c.setFont("Helvetica-Bold", 9)
        c.drawString(x + 3, y + 6, val)
    # notes (top left)
    c.setFont("Helvetica-Bold", 9)
    c.drawString(40, H - 50, "NOTES:")
    c.setFont("Helvetica", 8.5)
    for i, n in enumerate(notes, 1):
        c.drawString(40, H - 50 - 13 * i, f"{i}. {n}")


def _dim_h(c, x1, x2, y, text, ext_from=None):
    c.setLineWidth(0.4)
    c.line(x1, y, x2, y)
    for x in (x1, x2):
        c.line(x, y - 3, x, y + 3)
        if ext_from is not None:
            c.line(x, ext_from, x, y)
    c.setFont("Helvetica", 9)
    c.drawCentredString((x1 + x2) / 2, y + 3, text)


def _dim_v(c, y1, y2, x, text, ext_from=None):
    c.setLineWidth(0.4)
    c.line(x, y1, x, y2)
    for y in (y1, y2):
        c.line(x - 3, y, x + 3, y)
        if ext_from is not None:
            c.line(ext_from, y, x, y)
    c.setFont("Helvetica", 9)
    c.drawString(x + 4, (y1 + y2) / 2 - 3, text)


